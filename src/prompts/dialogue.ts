import { z } from 'zod';

export const DialogueSchema = z.object({
  lines: z.array(
    z.object({
      speaker: z.enum(['buyer_agent', 'seller_agent']),
      text: z.string(),
    }),
  ),
});

export const dialoguePrompt = (problemText: string, sellerSummary: string) => `
Разыграй короткий диалог (6 реплик) между двумя AI-агентами, которые проверяют,
подходят ли их компании друг другу.

Агент покупателя знает проблему (конфиденциально): """${problemText}"""
Агент продавца знает свою компанию: """${sellerSummary}"""

Правила:
- Агент покупателя НИКОГДА не раскрывает текст проблемы дословно. Он спрашивает по существу
  ("работали ли вы с X?", "какой срок?") и раскрывает ровно столько, сколько нужно для проверки.
- Агент продавца отвечает по делу, может задать уточняющий вопрос.
- Начинает buyer_agent, реплики чередуются, каждая 1-2 предложения, живой язык.
- Последняя реплика — вывод, стоит ли сводить людей.
`.trim();
